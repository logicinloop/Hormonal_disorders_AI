def predict_pcos(
    age,
    bmi,
    height_cm,
    weight_kg,
    waist_hip_ratio,
    systolic_bp,
    diastolic_bp,
    regular_exercise,
    fast_food
):

    input_data = pd.DataFrame([[
        age,
        bmi,
        height_cm,
        weight_kg,
        waist_hip_ratio,
        systolic_bp,
        diastolic_bp,
        regular_exercise,
        fast_food
    ]], columns=features)

    input_processed = preprocessor.transform(
        input_data
    )

    probability = model.predict(
        input_processed,
        verbose=0
    )[0][0]

    prediction = int(probability >= 0.5)

    return probability, prediction

