from tensorflow.keras.layers import Input, Multiply
from tensorflow.keras.models import Model
print("LANN layers imported successfully!")

input_dim = X_train_processed.shape[1]
inputs = Input(shape=(input_dim,))
attention_scores = Dense(
    input_dim,
    activation="softmax",
    name="feature_attention"
)(inputs)
attended_features = Multiply()([
    inputs,
    attention_scores
])
x = Dense(64, activation="relu")(attended_features)
x = Dropout(0.2)(x)
x = Dense(32, activation="relu")(x)
x = Dropout(0.2)(x)
outputs = Dense(1, activation="sigmoid")(x)
lann_model = Model(
    inputs=inputs,
    outputs=outputs,
    name="Lifestyle_Attention_Neural_Network"
)
