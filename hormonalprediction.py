def evaluate_thyroid_model(
    model,
    X_data,
    y_data,
    model_type="traditional"
):

    if model_type == "traditional":

        y_prob = (
            model.predict_proba(
                X_data
            )[:, 1]
        )

    else:

        y_prob = (
            model.predict(
                X_data,
                verbose=0
            ).ravel()
        )

    y_pred = (
        y_prob >= 0.5
    ).astype(int)

    return {
        "Accuracy": accuracy_score(
            y_data,
            y_pred
        ),
        "Precision": precision_score(
            y_data,
            y_pred,
            zero_division=0
        ),
        "Recall": recall_score(
            y_data,
            y_pred,
            zero_division=0
        ),
        "F1": f1_score(
            y_data,
            y_pred,
            zero_division=0
        ),
        "ROC-AUC": roc_auc_score(
            y_data,
            y_prob
        )
    }, y_pred, y_prob


