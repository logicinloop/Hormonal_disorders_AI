def standardize_result_table(df):
    df = df.copy()

    df.columns = [
        str(c).strip().replace("%", "").replace("-", "_")
        for c in df.columns
    ]

    rename_map = {}

    for c in df.columns:
        lower = c.lower()

        if lower == "model":
            rename_map[c] = "Model"

        elif lower == "accuracy":
            rename_map[c] = "Accuracy"

        elif lower == "precision":
            rename_map[c] = "Precision"

        elif lower == "recall":
            rename_map[c] = "Recall"

        elif lower == "f1":
            rename_map[c] = "F1"

        elif lower in ["roc_auc", "rocauc", "roc_auc_score"]:
            rename_map[c] = "ROC-AUC"

    df = df.rename(columns=rename_map)

    return df


